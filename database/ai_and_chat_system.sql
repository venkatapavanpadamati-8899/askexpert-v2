ALTER TABLE public.ai_fix_proposals ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_approvals ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.privacy_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.conversation_participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

-- Helper function: is_admin check
CREATE OR REPLACE FUNCTION public.check_is_admin()
RETURNS BOOLEAN LANGUAGE sql SECURITY DEFINER SET search_path = public STABLE AS $$
  SELECT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin');
$$;

-- Helper function: is_expert check
CREATE OR REPLACE FUNCTION public.check_is_expert()
RETURNS BOOLEAN LANGUAGE sql SECURITY DEFINER SET search_path = public STABLE AS $$
  SELECT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'expert');
$$;

-- issue_reports RLS
DROP POLICY IF EXISTS "Users can view own reports and Admins view all" ON public.issue_reports;
CREATE POLICY "Users can view own reports and Admins view all" ON public.issue_reports
  FOR SELECT USING (auth.uid() = reporter_id OR public.check_is_admin());

DROP POLICY IF EXISTS "Authenticated users can create issue reports" ON public.issue_reports;
CREATE POLICY "Authenticated users can create issue reports" ON public.issue_reports
  FOR INSERT WITH CHECK (auth.uid() = reporter_id);

DROP POLICY IF EXISTS "Admins can update issue reports" ON public.issue_reports;
CREATE POLICY "Admins can update issue reports" ON public.issue_reports
  FOR UPDATE USING (public.check_is_admin());

-- ai_fix_proposals RLS
DROP POLICY IF EXISTS "Admins can read ai proposals" ON public.ai_fix_proposals;
CREATE POLICY "Admins can read ai proposals" ON public.ai_fix_proposals
  FOR SELECT USING (public.check_is_admin() OR auth.uid() IS NOT NULL);

DROP POLICY IF EXISTS "Admins and service can manage ai proposals" ON public.ai_fix_proposals;
CREATE POLICY "Admins and service can manage ai proposals" ON public.ai_fix_proposals
  FOR ALL USING (public.check_is_admin() OR auth.uid() IS NOT NULL);

-- admin_approvals RLS
DROP POLICY IF EXISTS "Admins can manage approvals" ON public.admin_approvals;
CREATE POLICY "Admins can manage approvals" ON public.admin_approvals
  FOR ALL USING (public.check_is_admin());

-- audit_logs RLS
DROP POLICY IF EXISTS "Authenticated users can insert audit logs" ON public.audit_logs;
CREATE POLICY "Authenticated users can insert audit logs" ON public.audit_logs
  FOR INSERT WITH CHECK (auth.uid() IS NOT NULL);

DROP POLICY IF EXISTS "Admins can read audit logs" ON public.audit_logs;
CREATE POLICY "Admins can read audit logs" ON public.audit_logs
  FOR SELECT USING (public.check_is_admin());

-- privacy_settings RLS
DROP POLICY IF EXISTS "Users can view any user privacy setting for permission check" ON public.privacy_settings;
CREATE POLICY "Users can view any user privacy setting for permission check" ON public.privacy_settings
  FOR SELECT USING (true);

DROP POLICY IF EXISTS "Users can manage own privacy settings" ON public.privacy_settings;
CREATE POLICY "Users can manage own privacy settings" ON public.privacy_settings
  FOR ALL USING (auth.uid() = user_id);

-- conversations & participants RLS
DROP POLICY IF EXISTS "Participants can view conversations" ON public.conversations;
CREATE POLICY "Participants can view conversations" ON public.conversations
  FOR SELECT USING (
    EXISTS (
      SELECT 1 FROM public.conversation_participants
      WHERE conversation_id = public.conversations.id AND user_id = auth.uid()
    ) OR public.check_is_admin()
  );

DROP POLICY IF EXISTS "Authenticated users can create conversations" ON public.conversations;
CREATE POLICY "Authenticated users can create conversations" ON public.conversations
  FOR INSERT WITH CHECK (auth.uid() IS NOT NULL);

DROP POLICY IF EXISTS "Participants can view member rows" ON public.conversation_participants;
CREATE POLICY "Participants can view member rows" ON public.conversation_participants
  FOR SELECT USING (
    EXISTS (
      SELECT 1 FROM public.conversation_participants AS cp
      WHERE cp.conversation_id = public.conversation_participants.conversation_id AND cp.user_id = auth.uid()
    ) OR public.check_is_admin()
  );

DROP POLICY IF EXISTS "Users can join conversations" ON public.conversation_participants;
CREATE POLICY "Users can join conversations" ON public.conversation_participants
  FOR INSERT WITH CHECK (auth.uid() IS NOT NULL);

-- messages RLS
DROP POLICY IF EXISTS "Conversation participants can read messages" ON public.messages;
CREATE POLICY "Conversation participants can read messages" ON public.messages
  FOR SELECT USING (
    EXISTS (
      SELECT 1 FROM public.conversation_participants
      WHERE conversation_id = public.messages.conversation_id AND user_id = auth.uid()
    ) OR public.check_is_admin()
  );

DROP POLICY IF EXISTS "Participants can send messages" ON public.messages;
CREATE POLICY "Participants can send messages" ON public.messages
  FOR INSERT WITH CHECK (
    auth.uid() = sender_id AND
    EXISTS (
      SELECT 1 FROM public.conversation_participants
      WHERE conversation_id = public.messages.conversation_id AND user_id = auth.uid()
    )
  );

-- notifications RLS
DROP POLICY IF EXISTS "Users can manage their notifications" ON public.notifications;
CREATE POLICY "Users can manage their notifications" ON public.notifications
  FOR ALL USING (auth.uid() = user_id);

